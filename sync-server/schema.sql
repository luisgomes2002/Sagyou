-- D1 schema of the Sagyou sync Worker. Idempotent: safe to run again.
-- The server only holds opaque device ids, ciphertext and numbers.

CREATE TABLE IF NOT EXISTS devices (
  id TEXT PRIMARY KEY,            -- opaque id: HMAC(idKey, deviceId), 32 hex
  token_hash TEXT NOT NULL UNIQUE, -- SHA-256 hex of the device token
  name_cipher TEXT NOT NULL,      -- device name, encrypted by the client
  last_seen INTEGER NOT NULL,
  revoked_at INTEGER,
  wipe INTEGER NOT NULL DEFAULT 0,
  cursor INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS changes (
  seq INTEGER PRIMARY KEY AUTOINCREMENT,
  device TEXT NOT NULL,
  batch_id TEXT NOT NULL,         -- part of the AAD; needed to decrypt
  ciphertext TEXT NOT NULL,
  size INTEGER NOT NULL,
  created_at INTEGER NOT NULL,
  UNIQUE (device, batch_id)
);

CREATE TABLE IF NOT EXISTS invites (
  hash TEXT PRIMARY KEY,          -- SHA-256 hex of the invite; the invite itself never reaches the server's disk
  expires_at INTEGER NOT NULL,
  used_at INTEGER
);

-- One committed snapshot at a time; its parts live in snapshot_parts.
CREATE TABLE IF NOT EXISTS snapshots (
  id TEXT PRIMARY KEY,            -- uuid generated by the device
  seq_until INTEGER NOT NULL,
  parts INTEGER NOT NULL,
  device TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS snapshot_parts (
  snapshot_id TEXT NOT NULL,
  idx INTEGER NOT NULL,
  device TEXT NOT NULL,
  ciphertext TEXT NOT NULL,
  created_at INTEGER NOT NULL,
  PRIMARY KEY (snapshot_id, idx)
);

-- One authentication policy for the sync group. TOTP is AES-GCM encrypted with
-- TOTP_ENC_KEY, which lives only in the Worker's secret store.
CREATE TABLE IF NOT EXISTS auth (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  key_proof_hash TEXT NOT NULL,
  version INTEGER NOT NULL DEFAULT 0,
  totp_cipher TEXT,
  pending_totp_cipher TEXT,
  totp_confirmed INTEGER NOT NULL DEFAULT 0,
  backup_hashes TEXT NOT NULL DEFAULT '[]',
  fail_count INTEGER NOT NULL DEFAULT 0,
  locked_until INTEGER NOT NULL DEFAULT 0
);

-- ── Remote control (spec docs/specs/2026-11-03-controle-remoto-app.md) ───────────
-- Additive: running this file again on an existing D1 only creates these tables.

-- One 'pc' (the controlled PC) and the authorized phones ('controller').
CREATE TABLE IF NOT EXISTS device_roles (
  id TEXT PRIMARY KEY,            -- opaque device id
  role TEXT NOT NULL CHECK (role IN ('pc', 'controller')),
  created_at INTEGER NOT NULL
);

-- Sealed with the control subkey; deleted when read or expired.
CREATE TABLE IF NOT EXISTS control_messages (
  msg_id TEXT PRIMARY KEY,        -- part of the AAD; needed to decrypt
  to_device TEXT NOT NULL,
  from_device TEXT NOT NULL,
  ciphertext TEXT NOT NULL,
  expires_at INTEGER NOT NULL,
  created_at INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS control_messages_to ON control_messages (to_device);

-- Messages that passed the second factor on the restore route ("Restaurar
-- acesso"); the mark leaves with its message.
CREATE TABLE IF NOT EXISTS control_factor_checked (
  msg_id TEXT PRIMARY KEY,
  expires_at INTEGER NOT NULL
);

-- The PC's last heartbeat, sealed.
CREATE TABLE IF NOT EXISTS control_status (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  from_device TEXT NOT NULL,
  msg_id TEXT NOT NULL,
  ciphertext TEXT NOT NULL,
  at INTEGER NOT NULL
);

-- The ESP32 key, sealed by the PC; the Worker never reads it.
CREATE TABLE IF NOT EXISTS esp32_key (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  from_device TEXT NOT NULL,
  msg_id TEXT NOT NULL,
  ciphertext TEXT NOT NULL,
  at INTEGER NOT NULL
);

-- SHA-256 hex of the ESP32 token.
CREATE TABLE IF NOT EXISTS power_tokens (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  token_hash TEXT NOT NULL,
  created_at INTEGER NOT NULL
);

-- The pending power command, HMAC'd by the phone with the ESP32 key.
CREATE TABLE IF NOT EXISTS power_commands (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  cmd TEXT NOT NULL,
  at INTEGER NOT NULL,
  exp INTEGER NOT NULL,
  mac TEXT NOT NULL,
  taken_at INTEGER
);

-- The ESP32's last report, HMAC'd by the ESP32.
CREATE TABLE IF NOT EXISTS power_state (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  pc_ping INTEGER NOT NULL,
  last_result TEXT NOT NULL,
  at INTEGER NOT NULL,
  mac TEXT NOT NULL,
  last_poll INTEGER NOT NULL
);

-- FCM registration token of each controller.
CREATE TABLE IF NOT EXISTS push_tokens (
  id TEXT PRIMARY KEY,
  token TEXT NOT NULL,
  at INTEGER NOT NULL
);

-- Public Ed25519 key of the controlled PC (spec docs/specs/2026-11-09-selar-senha-remota.md):
-- a phone far from home seals the Sagyou password to it. Written only by the device
-- that holds the 'pc' role; cleared when another device becomes the PC.
CREATE TABLE IF NOT EXISTS pc_key (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  device_id TEXT NOT NULL,
  public_key TEXT NOT NULL,
  updated_at INTEGER NOT NULL
);

-- Whether the PC is expected to keep sending heartbeats (spec docs/specs/2026-11-13-mobile-aprovacoes-notificacoes.md).
-- The PC says it in clear (the heartbeat itself is sealed): true while it runs in controlled
-- mode, false when it is shut down or stops on purpose. The scheduled job warns the phones
-- ("PC sem sinal") once when watch is 1 and the last heartbeat (control_status.at) is old.
CREATE TABLE IF NOT EXISTS pc_watch (
  id INTEGER PRIMARY KEY CHECK (id = 1),
  watch INTEGER NOT NULL,
  notified_at INTEGER
);
